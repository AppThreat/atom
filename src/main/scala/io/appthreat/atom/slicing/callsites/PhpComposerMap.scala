package io.appthreat.atom.slicing.callsites

import io.shiftleft.codepropertygraph.Cpg
import io.shiftleft.semanticcpg.language.*

import scala.collection.mutable
import scala.util.Try

/** Which Composer package declares a class or a namespaced function, from the metadata php2atom
  * stores as config files while `vendor/` itself is not parsed: `vendor/composer/installed.json`
  * (each package's name, version and install path) and the autoload maps `autoload_classmap.php`,
  * `autoload_psr4.php` and `autoload_namespaces.php` (a class's file, or the directories a
  * namespace prefix maps to). A class is looked up in the class map first and then by the longest
  * PSR-4 prefix, the order Composer's own autoloader uses; the file it names, or the directory the
  * prefix names, belongs to the package whose install path holds it.
  *
  * The maps are generated by Composer in one fixed layout (`'Prefix\\' => array($vendorDir .
  * '/pkg/src')`), one entry per line, which is what the line pattern below reads; a file in any
  * other shape yields no entries and the source then treats every class the project does not
  * declare as external, as it does when there is no metadata at all.
  *
  * The graph's config file names carry the separators of the host that built the atom, so a name is
  * compared in its normalised form and its content is read from the node the name belongs to.
  */
final class PhpComposerMap(atom: Cpg):

  private final case class Package(root: String, name: String, version: String)

  /** The metadata files, those nearest the input root first and then by name. The graph holds
    * config files in the order their parts finished, which differs between builds; a class that the
    * maps of two Composer trees (a project and a tool directory with a `vendor/` each) both name
    * belongs to the nearest tree, whatever order the graph holds them in.
    */
  private val metadata = atom.configFile.l.filter(f =>
      PhpComposerMap.FileNames.exists(n => normalised(f.name).endsWith(s"composer/$n"))
  ).sortBy(f => (normalised(f.name).count(_ == '/'), normalised(f.name)))

  /** Whether the project carries Composer's installed-package record. */
  val present: Boolean =
      metadata.exists(f => normalised(f.name).endsWith("composer/installed.json"))

  private def normalised(name: String): String = name.replace('\\', '/')

  /** `vendor/composer/x.php` -> the directory Composer's `$vendorDir` names, and its parent. */
  private def vendorDirOf(name: String): String =
    val parts = normalised(name).split('/').toList
    parts.dropRight(2).mkString("/")

  private def join(base: String, rest: String): String =
    val all = (if base.isEmpty then Nil else base.split('/').toList) ++ rest.split('/').toList
    val out = mutable.ListBuffer.empty[String]
    all.foreach {
        case "" | "." => ()
        case ".."     => if out.nonEmpty then out.remove(out.size - 1)
        case segment  => out += segment
    }
    out.mkString("/")

  private lazy val packages: List[Package] =
      metadata.filter(f => normalised(f.name).endsWith("composer/installed.json")).flatMap { f =>
        val vendorDir = vendorDirOf(f.name)
        io.circe.parser.parse(f.content).toOption.toList.flatMap { json =>
          val entries = json.asArray.orElse(json.hcursor.downField("packages").focus.flatMap(
            _.asArray
          )).getOrElse(Vector.empty)
          entries.toList.flatMap { p =>
            val c = p.hcursor
            for
              name <- c.downField("name").as[String].toOption
              path <- c.downField("install-path").as[String].toOption
            yield Package(
              join(s"$vendorDir/composer", path),
              name,
              c.downField("version").as[String].getOrElse("")
            )
          }
        }
      }.sortBy(-_.root.length)

  private val Entry   = """^\s*'((?:[^'\\]|\\.)*)'\s*=>\s*(.*?),?\s*$""".r
  private val PathRef = """\$(vendorDir|baseDir)\s*\.\s*'([^']*)'""".r

  /** The entries of one autoload map: key (unescaped) and the project-relative paths it maps to. */
  private def entriesOf(fileName: String): List[(String, List[String])] =
      metadata.filter(f => normalised(f.name).endsWith(s"composer/$fileName")).flatMap { f =>
        val vendorDir = vendorDirOf(f.name)
        val baseDir   = vendorDir.split('/').dropRight(1).mkString("/")
        f.content.linesIterator.flatMap {
            case Entry(key, value) =>
                val paths = PathRef.findAllMatchIn(value).map { m =>
                    join(if m.group(1) == "vendorDir" then vendorDir else baseDir, m.group(2))
                }.toList
                Option.when(paths.nonEmpty)(key.replace("\\\\", "\\") -> paths)
            case _ => None
        }.toList
      }

  // the first tree's entry wins (the nearest, see `metadata`): the last of the reversed list
  private lazy val classMap: Map[String, (String, String)] =
      entriesOf("autoload_classmap.php").reverse.map { (cls, paths) =>
          cls.toLowerCase -> (cls, paths.head)
      }.toMap

  private lazy val prefixes: List[(String, List[String])] =
      (entriesOf("autoload_psr4.php") ++ entriesOf("autoload_namespaces.php"))
          .filter(_._1.nonEmpty).sortBy(-_._1.length)

  private def packageOfPath(path: String): Option[Package] =
      packages.find(p => path == p.root || path.startsWith(s"${p.root}/"))

  private def packageOfClass(cls: String): Option[Package] =
      classMap.get(cls.toLowerCase).flatMap((_, path) => packageOfPath(path)).orElse(
        prefixes.iterator.filter((prefix, _) => cls.toLowerCase.startsWith(prefix.toLowerCase))
            .flatMap((_, dirs) => dirs.iterator.flatMap(packageOfPath)).nextOption()
      )

  /** The package that declares a class, or true for every class when there is no metadata. */
  def declaredByPackage(cls: String): Boolean = !present || packageOfClass(cls).isDefined

  /** A class as Composer's class map spells it, else as written. */
  def declaredCase(cls: String): String = classMap.get(cls.toLowerCase).map(_._1).getOrElse(cls)

  def purlOfClass(cls: String): String = packageOfClass(cls).map(purl).getOrElse("")

  /** The name of the package that declares a class, as `installed.json` spells it. */
  def packageNameOfClass(cls: String): Option[String] = packageOfClass(cls).map(_.name)

  private def namespaceOf(fn: String): Option[String] =
      Option(fn.lastIndexOf('\\')).filter(_ > 0).map(i => fn.substring(0, i + 1))

  private def packageOfNamespace(fn: String): Option[Package] =
      namespaceOf(fn).flatMap { ns =>
          prefixes.iterator.filter((prefix, _) => ns.toLowerCase.startsWith(prefix.toLowerCase))
              .flatMap((_, dirs) => dirs.iterator.flatMap(packageOfPath)).nextOption()
      }

  /** A global function has no namespace to map by and is assumed to be a package's; a namespaced
    * one must sit in a namespace a package declares.
    */
  def functionExternal(fn: String): Boolean =
      !present || !fn.contains('\\') || packageOfNamespace(fn).isDefined

  def purlOfFunction(fn: String): String = packageOfNamespace(fn).map(purl).getOrElse("")

  private def purl(p: Package): String =
      if p.version.isEmpty then s"pkg:composer/${p.name}"
      else s"pkg:composer/${p.name}@${p.version}"
end PhpComposerMap

object PhpComposerMap:
  val FileNames: List[String] =
      List(
        "installed.json",
        "autoload_classmap.php",
        "autoload_psr4.php",
        "autoload_namespaces.php"
      )
